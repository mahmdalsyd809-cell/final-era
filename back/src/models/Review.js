const mongoose = require('mongoose');

/**
 * ========================================================
 * موديل التعليقات / المراجعات (Review Model)
 * ========================================================
 * تعليقات عامة على المتجر — بدون ربط بمنتج معين:
 *  - المستخدم الذي كتب التعليق
 *  - التقييم بالنجوم (1 إلى 5)
 *  - نص التعليق
 *  - عنوان التعليق (اختياري)
 *  - اسم العميل (للعرض السريع بدون populate)
 * ========================================================
 */

const reviewSchema = new mongoose.Schema(
  {
    // ── المستخدم الذي كتب التعليق ─────────────────────────
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'المستخدم مطلوب']
    },

    // ── اسم العميل (cached للعرض السريع) ──────────────────
    userName: {
      type: String,
      required: [true, 'اسم العميل مطلوب'],
      trim: true
    },

    // ── التقييم بالنجوم (1-5) ─────────────────────────────
    rating: {
      type: Number,
      required: [true, 'التقييم مطلوب'],
      min: [1, 'أقل تقييم هو 1'],
      max: [5, 'أعلى تقييم هو 5']
    },

    // ── نص التعليق ────────────────────────────────────────
    comment: {
      type: String,
      required: [true, 'نص التعليق مطلوب'],
      trim: true,
      maxlength: [1000, 'التعليق لا يمكن أن يتجاوز 1000 حرف']
    },

    // ── عنوان التعليق (اختياري) ───────────────────────────
    title: {
      type: String,
      default: '',
      trim: true,
      maxlength: [100, 'العنوان لا يمكن أن يتجاوز 100 حرف']
    }
  },
  {
    timestamps: true
  }
);

// ── كل مستخدم يقدر يكتب تعليق واحد فقط ──────────────────
reviewSchema.index({ user: 1 }, { unique: true });

// ── Index للترتيب حسب التاريخ ─────────────────────────────
reviewSchema.index({ createdAt: -1 });

module.exports = mongoose.model('Review', reviewSchema);
